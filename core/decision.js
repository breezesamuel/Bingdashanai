// ================= 决策中心正确率：多信号加权匹配 =================
// 信号S1 关键词权重：KEYWORDS 命中(长词更特异，权重按长度递增) + 关键词在框架名/描述也命中(语义再扣分)
// 信号S2 文本重叠：主题中的中文二元词组与框架名/描述的重合度
// 信号S3 类别先验：命中词属于某 cat 的次数作为类别热度加权
// 消歧：同一关键词命中多个框架时，命中最多的、最特异的框架胜出（总分数自然体现）
const FILLER = ['我要', '我想', '请问', '帮我', '一下', '关于', '如何', '怎么', '该不该', '要不要', '怎么样', '怎么办', '做个', '做一个', '进行', '分析', '分析一下', '看下', '看看', '给个', '给'];

function cleanTopic(t) {
  let s = String(t || '').trim();
  FILLER.forEach(f => { s = s.split(f).join(' '); });
  return s.replace(/\s+/g, ' ').trim();
}

function wordPairs(text) {
  const mm = (String(text).match(/[\u4e00-\u9fa5]{2,}/g) || []).join('');
  const out = new Set();
  for (let i = 0; i + 1 < mm.length; i++) if (mm.slice(i, i + 2) !== '的东' && mm.slice(i, i + 2)) out.add(mm.slice(i, i + 2));
  for (let i = 0; i + 2 < mm.length; i++) out.add(mm.slice(i, i + 3));
  return out;
}

function suggestV2(topic) {
  const t = cleanTopic(topic);
  // 空主题：无信息可匹配，直接给通用决策框架兜底（不装懂）
  if (!t) {
    const d = ['swot', 'pdca', '5w1h'].map(id => {
      const f = FRAMEWORKS.find(x => x.id === id);
      return { id: f.id, name: f.name, cat: f.cat, emoji: f.emoji, score: 0 };
    });
    return { topic: '当前主题', raw: String(topic || ''), matched: false, top1: d[0].id,
      picks: d, confidence: 0, note: '无主题信息，已给通用框架兜底——请补充具体问题以获得高置信推荐。' };
  }
  const tl = t.toLowerCase();
  const pairs = wordPairs(t);
  const scored = FRAMEWORKS.map(f => {
    const hayName = (f.name + ' ' + f.cat).toLowerCase();
    const hayFull = (f.name + ' ' + f.desc + ' ' + f.cat).toLowerCase();
    let s = 0;
    // S1 关键词（特异：命中词越长分越高；单字命中门槛高，防误伤；同时命中框架名则 ×1.3 语义加成）
    (KEYWORDS[f.id] || []).forEach(k => {
      if (tl.includes(k.toLowerCase())) {
        s += (k.length <= 1 ? 1 : 4 + Math.min(6, k.length * 1.5));
        if (hayName.includes(k.toLowerCase())) s += 3;
      }
    });
    // S2 文本二元组重叠（与名称/描述契合度）
    pairs.forEach(p => {
      if (hayFull.includes(p)) s += 2;
      if (hayName.includes(p)) s += 1;
    });
    // S3 类别热度：几个热门类别本身是常见提问场景
    const catHot = { 战略: 1, 运营: 1, 风险: 2 };
    if (catHot[f.cat]) s += catHot[f.cat];
    return { id: f.id, name: f.name, cat: f.cat, emoji: f.emoji, score: Math.round(s * 10) / 10 };
  }).filter(x => x.score > 0);
  scored.sort((a, b) => b.score - a.score);
  const top = scored.slice(0, 3);
  const confidence = top.length >= 2 && top[0].score > 0
    ? Math.round(top[0].score / (top[0].score + top[1].score) * 100)
    : (top.length ? 100 : 0);
  const picks = top.length ? top : ['swot', 'pdca', '5w1h'].map(id => {
    const f = FRAMEWORKS.find(x => x.id === id);
    return { id: f.id, name: f.name, cat: f.cat, emoji: f.emoji, score: 0 };
  });
  return {
    topic: t || '当前主题', raw: String(topic || ''),
    matched: top.length > 0, top1: picks[0].id,
    picks, confidence,
    note: confidence >= 60 ? '匹配置信度较高，可直接采用推荐框架。'
      : confidence >= 40 ? '匹配一般，建议结合次选框架交叉验证。'
        : '无强匹配，已给通用框架兜底，请补充主题细节。'
  };
}

