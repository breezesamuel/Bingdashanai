// 尊严文案扫描：命中禁词即报（模板与 UGC 全过）
function scanDignity(text) {
  const t = String(text || '');
  const hits = DIGNITY_BANNED.filter(w => t.includes(w));
  return { passes: hits.length === 0, hits };
}
// 禁比较句/金额句（T1 内容过滤用）
function scanForbidden(t) {
  const txt = String(t || '');
  const comp = (txt.match(/(比他|比她|比谁|更幸运|我好多了|别人都不如)/g) || []);
  const money = (txt.match(/(¥|￥|\d+万|\d+元|\d+块|负债\d+)/g) || []).filter(x => x !== '万元');
  return { comp, money: money.slice(0, 10) };
}

// 危机词扫描：命中 → 强制升级为 12356 转介卡（危机语境，最高优先）
function scanCrisis(text) {
  const t = String(text || '');
  const hits = CRISIS_WORDS.filter(w => t.includes(w));
  return hits.length
    ? { crisis: true, hits, card: '【转介卡 · 优先于一切】如有伤害自己的想法，请拨打 12356（24h）或前往最近医院心理科/急诊。' }
    : { crisis: false, hits: [] };
}

function list() {
  return MANUALS.map(m => ({ no: m.no, slug: m.slug, title: m.title, keywords: m.keywords, crisis: !!m.crisis, commerce: m.commerce }));
}
function get(noOrSlug) {
  return MANUALS.find(m => m.no === Number(noOrSlug) || m.slug === String(noOrSlug) || m.title === String(noOrSlug)) || null;
}

