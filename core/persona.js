function score(answers) {
  const m = { a: 0, b: 0, c: 0, d: 0, e: 0, f: 0 };
  answers.forEach((letter, i) => {
    const l = String(letter || '').trim().toLowerCase();
    if (m[l] != null) m[l]++;
    else if (i < QUESTIONS.length && (answers[i] == null)) { /* 空题跳过 */ }
  });
  const ranked = Object.entries(m).sort((x, y) => y[1] - x[1]);
  const topK = ranked[0][0];
  const secondK = ranked[1][0];
  const top = TYPES.find(t => t.key === topK) || TYPES[0];
  const second = TYPES.find(t => t.key === secondK) || TYPES[1];
  const total = answers.filter(x => m[String(x).toLowerCase()] != null).length;
  return { counts: m, ranked, top: topK, second: secondK, type: top.label, sub: top.sub, topAdv: top.adv, secondLabel: second.label, total };
}

// 完整测试：20 题
function runTest(answers, extra) {
  if (!answers || answers.length < QUESTIONS.length) throw new Error('需提交 ' + QUESTIONS.length + ' 个答案（每题一个字母 a–f）');
  const sc = score(answers.slice(0, QUESTIONS.length));
  const rec = store.push('persona', {
    kind: 'test20',
    answers: answers.slice(0, QUESTIONS.length),
    type: sc.type, sub: sc.sub, top: sc.top, second: sc.second, counts: sc.counts,
    note: String((extra && extra.note) || '')
  }, '完成六型决策人格测试', sc.type + ' ' + sc.counts[sc.top] + '/20');
  return { ok: true, id: rec.id, ...sc, counts: sc.counts, share: shareCard(sc) };
}

// 快速抉择测试：随机抽 3 题 → 主打类型
function runQuick(seedAnswers, extra) {
  const ans = (seedAnswers || []);
  const sc = score(ans);
  sc.total = ans.length;
  if (!ans.length) throw new Error('需至少提交 1 个答案');
  const rec = store.push('persona', {
    kind: 'quick3',
    answers: ans,
    type: sc.type, sub: sc.sub, top: sc.top, second: sc.second, counts: sc.counts,
    note: String((extra && extra.note) || '')
  }, '完成快速抉择测试', sc.type + ' ' + ans.length + '题');
  return { ok: true, id: rec.id, ...sc, share: null, quick: true };
}

// 分享卡（FINAL-1.1 P2：分享卡 → 转化）
function shareCard(sc) {
  const top = TYPES.find(t => t.key === sc.top) || TYPES[0];
  const second = TYPES.find(t => t.key === sc.second) || TYPES[1];
  return {
    title: '我的六型决策人格',
    line1: '我是『' + top.label + '·' + top.sub + '』',
    line2: '底色里还有一点 ' + second.label + '（如何权衡、何时起身、向谁开口）',
    adv: top.adv,
    footer: '—— 来自「我一直在」：测完这道题，去看看自己真实的那道题。',
    stamp: new Date().toDateString()
  };
}

